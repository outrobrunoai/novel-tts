  const catalogs = Object.freeze({pt, en, es});
  let requestedLanguage = 'auto';
  let current = detectFirefoxLanguage();

  function detectFirefoxLanguage(browserApi = globalThis.browser) {
    let value = '';
    try { value = browserApi?.i18n?.getUILanguage?.() || ''; } catch { /* Use locale fallback. */ }
    if (!value) value = globalThis.Intl?.DateTimeFormat?.().resolvedOptions?.().locale || '';
    const code = String(value).toLowerCase().split(/[-_]/)[0];
    return ['pt', 'en', 'es'].includes(code) ? code : 'pt';
  }
  function normalizeChoice(value) { return ['auto', 'pt', 'en', 'es'].includes(value) ? value : 'auto'; }
  function resolveChoice(value, browserApi) {
    const normalized = normalizeChoice(value);
    return normalized === 'auto' ? detectFirefoxLanguage(browserApi) : normalized;
  }
  function setLanguage(value, browserApi = globalThis.browser, scope = null) {
    requestedLanguage = normalizeChoice(value);
    current = resolveChoice(requestedLanguage, browserApi);
    const documentElement = scope?.nodeType === 9 ? scope.documentElement : null;
    if (documentElement) documentElement.lang = current;
    if (scope) apply(scope);
    return current;
  }
  function t(key, values = {}) {
    const message = catalogs[current]?.[key] ?? pt[key];
    if (typeof message !== 'string') return key;
    return message.replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  }
  function apply(scope = globalThis.document) {
    if (!scope?.querySelectorAll) return;
    for (const element of scope.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
    for (const element of scope.querySelectorAll('[data-i18n-title]')) element.title = t(element.dataset.i18nTitle);
    for (const element of scope.querySelectorAll('[data-i18n-aria-label]')) element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    for (const element of scope.querySelectorAll('[data-i18n-placeholder]')) element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
    for (const element of scope.querySelectorAll('[data-i18n-label]')) {
      const textNode = [...element.childNodes].find(node => node.nodeType === 3 && node.textContent.trim());
      if (textNode) textNode.textContent = `${t(element.dataset.i18nLabel)} `;
    }
  }
  function validSettingsResponse(response) {
    const schema = root.settingsSchema;
    if (!schema) return false;
    const expectedKeys = [...schema.keys].sort();
    const acceptedKeys = Array.isArray(response?.accepted_keys) ? [...response.accepted_keys].sort() : null;
    return response?.ok === true && response.settings_protocol === schema.protocolVersion &&
      response.implementation === schema.implementation && Number.isInteger(response.revision) &&
      response.revision >= 0 && acceptedKeys &&
      JSON.stringify(acceptedKeys) === JSON.stringify(expectedKeys) &&
      schema.valid('interfaceLanguage', response.settings?.interfaceLanguage);
  }
  async function loadFromBackground(browserApi = globalThis.browser) {
    const response = await browserApi.runtime.sendMessage({type: 'settings-get'});
    if (!validSettingsResponse(response)) throw new Error('settings unavailable');
    return setLanguage(response.settings.interfaceLanguage, browserApi, globalThis.document);
  }
  function observeSettings(browserApi = globalThis.browser, onLanguageChanged = null) {
    const listener = (changes, areaName) => {
      if (areaName !== 'local' || !changes?.nlrSettings?.newValue) return;
      const choice = changes.nlrSettings.newValue.interfaceLanguage;
      if (['auto', 'pt', 'en', 'es'].includes(choice)) {
        setLanguage(choice, browserApi, globalThis.document);
        try { onLanguageChanged?.(current); } catch { /* UI refresh is best effort. */ }
      }
    };
    browserApi?.storage?.onChanged?.addListener(listener);
    return () => browserApi?.storage?.onChanged?.removeListener(listener);
  }

  root.i18n = Object.freeze({catalogs, t, apply, setLanguage, normalizeChoice, resolveChoice,
    detectFirefoxLanguage, loadFromBackground, observeSettings, validSettingsResponse,
    currentLanguage: () => current, selectedLanguage: () => requestedLanguage});
